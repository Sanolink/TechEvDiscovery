const $Gas = Java.loadClass('mekanism.api.chemical.gas.Gas')
const $GasBuilder = Java.loadClass('mekanism.api.chemical.gas.GasBuilder')

StartupEvents.registry('mekanism:gas', event => {
    event.createCustom('mekanism:hypermatter', () => new $Gas($GasBuilder.builder().color(0x3EB9B9)))
    event.createCustom('mekanism:hyperphasium', () => new $Gas($GasBuilder.builder().color(0x6976C7)))
})